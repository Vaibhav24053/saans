import {
  AlertTriangle,
  CheckCircle2,
  Cpu,
  Globe2,
  Info,
  Leaf,
  Shield,
  Sparkles,
} from 'lucide-react';
import { getAqiCategory } from '@shared/aqi';
import type { AqiScale } from '@shared/types';

export function AqiStatusBadge({
  aqi,
  scale,
  size = 'md',
}: {
  aqi: number | null;
  scale: AqiScale;
  size?: 'sm' | 'md' | 'lg';
}) {
  const cat = getAqiCategory(aqi, scale);
  const Icon =
    cat.severity <= 1
      ? CheckCircle2
      : cat.severity <= 3
        ? Info
        : AlertTriangle;

  const sizeClass =
    size === 'sm'
      ? 'text-xs px-2.5 py-0.5 gap-1'
      : size === 'lg'
        ? 'text-sm px-3.5 py-1.5 gap-2'
        : 'text-xs px-3 py-1 gap-1.5';

  return (
    <span
      className={`inline-flex items-center font-semibold rounded-full border ${sizeClass}`}
      style={{
        color: cat.textColor,
        backgroundColor: cat.bgColor,
        borderColor: cat.borderColor,
      }}
    >
      <Icon className={size === 'lg' ? 'w-4 h-4 shrink-0' : 'w-3.5 h-3.5 shrink-0'} />
      <span>{cat.label}</span>
    </span>
  );
}

export function AiSourceBadge({
  source,
  model,
  fallbackReason,
}: {
  source: 'gemini' | 'fallback';
  model?: string;
  fallbackReason?: string;
}) {
  if (source === 'gemini') {
    return (
      <span
        className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-medium bg-[#E6F0EB] text-[#1B4332] border border-[#C3DCD0]"
        title={`Generated server-side with Google ${model ?? 'gemini-3.5-flash-lite'}`}
      >
        <Sparkles className="w-3.5 h-3.5" />
        <span>Gemini AI · {model ?? 'gemini-3.5-flash-lite'}</span>
      </span>
    );
  }

  return (
    <span
      className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-medium bg-[#F4F1E8] text-[#5C5340] border border-[#DFD8C5]"
      title={fallbackReason || 'Generated by SAANS rules-based fallback engine'}
    >
      <Cpu className="w-3.5 h-3.5" />
      <span>Rules-Based Fallback</span>
    </span>
  );
}

export function ImpactCategoryBadge({
  category,
}: {
  category: 'personal_exposure' | 'wider_emissions' | 'both' | 'informational';
}) {
  if (category === 'personal_exposure') {
    return (
      <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-semibold bg-[#E8F2F8] text-[#1F5489] border border-[#C8DFEE]">
        <Shield className="w-3 h-3" />
        Personal Exposure
      </span>
    );
  }
  if (category === 'wider_emissions') {
    return (
      <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-semibold bg-[#E6F4EC] text-[#1E563B] border border-[#BFE2CE]">
        <Leaf className="w-3 h-3" />
        Wider Emissions
      </span>
    );
  }
  if (category === 'both') {
    return (
      <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-semibold bg-[#EEF2EA] text-[#264A37] border border-[#CBD8C3]">
        <Globe2 className="w-3 h-3" />
        Exposure + Emissions
      </span>
    );
  }
  return (
    <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-semibold bg-[#F0EEE7] text-[#4A5550] border border-[#DDD8CC]">
      <Info className="w-3 h-3" />
      Air Context
    </span>
  );
}
